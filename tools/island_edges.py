"""Write a per-column edge table for named UV islands, from a template's wire.

    python tools/island_edges.py scratch/ray/tpl src/ray_islands.py 2053 \\
           NOSE_TIP=7 NOSE=4 COWL=8 DECK=20 FLANK=2 REAR=6 LOWER=11 POD=0 SILL=13

Island indices are the ones `tools/probe_islands.py <mod> <tpl> list` prints.
For each island it walks every 4th texture column and records the island's
(top, bottom) row there, so artwork can be hung off a sloping island edge
instead of a constant row - the trick that made the F4's engine-cover stripes
identical on both sides (docs/PANEL-PROBING.md section 8).  Generalised from
tools/f4_islands_gen.py for the Ray FF1600, 2026-09-14.

The template is not in git; the generated table is.
"""
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

if len(sys.argv) < 5:
    sys.exit(__doc__)
TPL, OUT, MIRROR = sys.argv[1], sys.argv[2], int(sys.argv[3])
SPECS = [s.split("=") for s in sys.argv[4:]]
STEP = 4

a = np.asarray(Image.open(os.path.join(TPL, "Wire.png"))).astype(int)
al = a[..., 3] > 40
green = al & (a[..., 1] > 150) & (a[..., 0] < 120) & (a[..., 2] < 120)
lab, n = ndimage.label(~ndimage.binary_dilation(green, iterations=1))
sizes = ndimage.sum(np.ones_like(lab), lab, range(1, n + 1))
rows = []
for i, sl in enumerate(ndimage.find_objects(lab)):
    if sizes[i] < 900:
        continue
    ys, xs = sl
    if xs.start == 0 and ys.start == 0 and xs.stop > 2000 and ys.stop > 2000:
        continue
    rows.append((int(sizes[i]), i + 1, xs.start, ys.start,
                 xs.stop - xs.start, ys.stop - ys.start))
rows.sort(reverse=True)

out = ['"""Per-column UV island edges, generated by tools/island_edges.py from',
       'the car template\'s green wire outlines.  The template is not in git;',
       'this table is.  Each entry: texture x -> (y_top, y_bottom) of that',
       'island at that column.  Right side = y\' = MIRROR - y."""', '']
for name, idx in SPECS:
    area, l, x, y, w, h = rows[int(idx)]
    mask = lab == l
    tbl = {}
    for xx in range(x, x + w, STEP):
        col = np.where(mask[:, xx])[0]
        if len(col):
            tbl[xx] = (int(col.min()), int(col.max()))
    out.append("# island %s: bbox (%d, %d, %d, %d), area %d" % (idx, x, y, w, h, area))
    out.append("%s_BBOX = (%d, %d, %d, %d)" % (name, x, y, w, h))
    out.append("%s = {" % name)
    items = list(tbl.items())
    for i in range(0, len(items), 6):
        out.append("    " + ", ".join("%d: (%d, %d)" % (k, v[0], v[1])
                                      for k, v in items[i:i + 6]) + ",")
    out.append("}")
    out.append("")
    print("%-10s island %-3s bbox (%d,%d,%d,%d)  %d columns" % (name, idx, x, y, w, h, len(tbl)))
out.append("MIRROR = %d   # right-side texture y = MIRROR - left y; x is the same" % MIRROR)
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote", OUT)
